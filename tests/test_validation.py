"""Recovered estimates vs. data/truth/planted_effects.json."""
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]


def within(est, value):
    return est["ci_low_pp"] <= value <= est["ci_high_pp"]


def test_primary_effect_recovered(results, truth):
    t = truth["realized"]
    assert within(results["cuped_no_show"], t["effect_no_show_pp"])
    assert within(results["primary_no_show"], t["effect_no_show_pp"])
    assert results["cuped_no_show"]["ci_high_pp"] < 0


def test_guardrails_recovered(results, truth):
    t = truth["realized"]
    assert within(results["late_cancel"], t["effect_late_cancel_pp"])
    assert within(results["cuped_unfilled"], t["effect_unfilled_pp"])
    refill_diff = 100 * (t["by_variant"]["treatment"]["refill_late_cancel"] - t["by_variant"]["control"]["refill_late_cancel"])
    assert within(results["refill_of_late_cancels"], refill_diff)
    assert results["late_cancel"]["diff_pp"] > 0 and results["cuped_unfilled"]["diff_pp"] < 0


def test_payer_effects_recovered(results, truth):
    seg = {(s["dimension"], s["segment"], s["metric"]): s for s in results["segments"]}
    for p, v in truth["realized"]["by_payer"].items():
        assert within(seg[("payer", p, "is_no_show")], v["effect_pp"]), p
    assert any(i["term"] == "medicaid" for i in results["interactions_significant"])


def test_cuped(results, truth):
    assert abs(results["cuped_rho_patient_level"] - truth["realized"]["rho_pre_vs_experiment"]) < 0.02
    assert 0.45 <= truth["realized"]["rho_pre_vs_experiment"] <= 0.65
    assert results["cuped_no_show"]["variance_reduction"] > 0.25


def test_srm_localized(results, truth):
    bug = truth["parameters"]["srm_bug"]
    ex = results["srm"]["exclusions"]
    assert len(ex) == 1
    assert (ex[0]["clinic_id"], ex[0]["date_from"], ex[0]["date_to"]) == (bug["clinic"], bug["from"], bug["to"])
    assert ex[0]["treatment_in_window"] == 0
    assert results["srm"]["overall_after"]["p_value"] > 0.001


def test_power_matches_design_doc(results):
    pw = results["power"]
    doc = (ROOT / "docs" / "experiment_design.md").read_text()
    assert round(pw["n_per_arm_unclustered"], -2) == 7700 and "7,700" in doc
    assert round(pw["n_per_arm_clustered"], -2) == 9600 and "9,600" in doc
    assert pw["design_effect_planned"] == pytest.approx(1.24)


def test_readme_numbers_match_results(results):
    readme = (ROOT / "README.md").read_text()
    assert f"{results['cuped_no_show']['diff_pp']:+.2f}" in readme
    assert f"{results['cuped_unfilled']['diff_pp']:+.2f}" in readme
    assert results["decision"] in readme
    assert "{" not in re.sub(r"```.*?```", "", readme, flags=re.S)  # no unfilled template keys
    assert "All data in this repository is synthetic, generated by `src/generate_data.py` (seed 42)" in readme
